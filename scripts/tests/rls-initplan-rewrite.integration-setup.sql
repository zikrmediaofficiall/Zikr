\set ON_ERROR_STOP on

CREATE SCHEMA auth;
CREATE OR REPLACE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
AS $$ SELECT '11111111-1111-4111-8111-111111111111'::uuid $$;
CREATE OR REPLACE FUNCTION auth.jwt()
RETURNS jsonb
LANGUAGE sql
STABLE
AS $$ SELECT '{"role":"authenticated"}'::jsonb $$;
GRANT USAGE ON SCHEMA auth TO PUBLIC;
GRANT EXECUTE ON FUNCTION auth.uid() TO PUBLIC;
GRANT EXECUTE ON FUNCTION auth.jwt() TO PUBLIC;

CREATE TABLE public.rls_initplan_test (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL,
  tenant_id uuid NOT NULL,
  payload text NOT NULL
);
ALTER TABLE public.rls_initplan_test ENABLE ROW LEVEL SECURITY;

CREATE POLICY raw_uid_jwt_policy
  ON public.rls_initplan_test
  FOR ALL
  USING (owner_id = auth.uid() AND auth.jwt() ->> 'role' = 'authenticated')
  WITH CHECK (owner_id = auth.uid() AND auth.jwt() ->> 'role' = 'authenticated');

-- A mixed expression must have only the raw call rewritten; the existing
-- SELECT initplan must not be wrapped a second time.
CREATE POLICY mixed_uid_policy
  ON public.rls_initplan_test
  FOR SELECT
  USING (owner_id = (SELECT auth.uid()) AND tenant_id = auth.uid());

-- Already-wrapped UID remains stable while a raw JWT call is repaired.
CREATE POLICY wrapped_uid_raw_jwt_policy
  ON public.rls_initplan_test
  FOR SELECT
  USING (owner_id = (SELECT auth.uid()) AND auth.jwt() ->> 'role' = 'admin');

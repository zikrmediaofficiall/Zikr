import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const read = (path) => readFileSync(path, "utf8");
const script = read("scripts/sync-quran-english.ts");
const migration = read("supabase/migrations/20261121100000_quran_english_translation_provenance.sql");
const quranService = read("src/features/quran/services/quran.ts");
const quranServer = read("src/features/quran/services/quran-server.ts");
const types = read("src/lib/types/supabase.ts");
const packageJson = JSON.parse(read("package.json"));
const circle = read(".circleci/config.yml");
const workflow = read(".github/workflows/english-content-sync.yml");

assert.equal(packageJson.scripts["sync:quran:en"], "tsx scripts/sync-quran-english.ts");
assert.equal(packageJson.scripts["quran:canonical:check"], "node scripts/verify-quran-canonicalization.mjs && node scripts/tests/quran-english-sync-contract.test.mjs");
assert.ok(script.includes('const EDITION = "en.pickthall"'));
assert.ok(script.includes("https://api.alquran.cloud/v1"));
assert.ok(script.includes('"/surah/" + surahId + "/" + EDITION'));
assert.ok(script.includes("data.edition?.identifier !== EDITION"));
assert.ok(script.includes("data.edition?.language !== \"en\""));
assert.ok(script.includes("PAGE_SIZE = 1_000") && script.includes("offset="));
assert.ok(script.includes("source.text_ar") && script.includes("text_ar: source.text_ar"));
assert.ok(script.includes("admin_sync_quran_english_batch"));
assert.ok(!script.includes("generateGeminiText") && !script.includes("GEMINI_API_KEY"));
assert.ok(migration.includes("text_en_edition text"));
assert.ok(migration.includes("CHECK (text_en_edition IS NULL OR text_en_edition = 'en.pickthall')"));
assert.ok(migration.includes("SECURITY INVOKER"));
assert.ok(migration.includes("target.text_ar = incoming.text_ar"));
assert.ok(migration.includes("NULLIF(pg_catalog.btrim(target.text_en), '') IS NULL"));
assert.ok(migration.includes("text_en_edition = p_edition"));
assert.ok(migration.includes("REVOKE ALL ON FUNCTION public.admin_sync_quran_english_batch"));
assert.ok(migration.includes("GRANT EXECUTE ON FUNCTION public.admin_sync_quran_english_batch"));
for (const source of [quranService, quranServer]) assert.ok(source.includes("text_en_edition"));
assert.ok(types.includes("text_en_edition: string | null"));
assert.ok(types.includes("text_en_edition?: string | null"));
assert.ok(circle.includes("pnpm sync:quran:en") && circle.includes("quran_status"));
assert.ok(workflow.includes("pnpm sync:quran:en") && workflow.includes("quran_status"));
console.log("Source-attributed English Quran synchronization contracts passed.");
